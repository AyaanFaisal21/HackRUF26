const j = async (r) => { if (!r.ok) { let t = await r.text(); try { t = JSON.parse(t).detail ?? t; } catch {} throw new Error(t); } return r.json(); };
const post = (url, body) => fetch(url, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body ?? {}) }).then(j);
export const api = {
  health: () => fetch("/api/health").then(j),
  stats: () => fetch("/api/stats").then(j),
  factsDaily: () => fetch("/api/stats/facts_daily").then(j),
  patients: (q, kind) => fetch(`/api/patients?${new URLSearchParams({ ...(q ? { q } : {}), ...(kind ? { kind } : {}) })}`).then(j),
  patient: (id) => fetch(`/api/patients/${id}`).then(j),
  patientFacts: (id, concept) => fetch(`/api/patients/${id}/facts${concept ? `?concept=${concept}` : ""}`).then(j),
  documents: (status) => fetch(`/api/documents${status ? `?status=${status}` : ""}`).then(j),
  document: (id) => fetch(`/api/documents/${id}`).then(j),
  ingest: (body) => post("/api/documents", body),
  upload: (formData) => fetch("/api/documents/upload", { method: "POST", body: formData }).then(j),
  imageUrl: (id) => `/api/documents/${id}/image`,
  search: (q, patient_id) => fetch(`/api/search?${new URLSearchParams({ q, ...(patient_id ? { patient_id } : {}) })}`).then(j),
  forms: () => fetch("/api/forms").then(j),
  fill: (pid, form_id, visit_date, second_opinion) => post(`/api/patients/${pid}/forms`, { form_id, visit_date, second_opinion }),
  instance: (id) => fetch(`/api/forms/instances/${id}`).then(j),
  decide: (id, key, d) => post(`/api/forms/instances/${id}/fields/${key}`, d),
  sign: (id, actor) => post(`/api/forms/instances/${id}/sign`, { actor }),
  explain: (id, key) => post(`/api/forms/instances/${id}/fields/${key}/explain`),
  exportForm: (id) => fetch(`/api/forms/instances/${id}/export`).then(j),
  history: (id) => fetch(`/api/forms/instances/${id}/history`).then(j),
  queue: () => fetch("/api/queue").then(j),
  metrics: (refresh) => fetch(`/api/metrics${refresh ? "?refresh=true" : ""}`).then(j),
};
